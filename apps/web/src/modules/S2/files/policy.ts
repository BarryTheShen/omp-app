const fileEditModeSchema = z.enum(["apply_patch", "hashline", "patch", "replace", "sloppy"]);
const booleanSchema = z.boolean();
const numberSchema = z.number().finite();

export type FileEditMode = z.infer<typeof fileEditModeSchema>;

export type FilesEditingPolicy = {
  readonly mode: FileEditMode;
  readonly fuzzyMatch: boolean;
  readonly fuzzyThreshold: number;
  readonly streamingAbort: boolean;
  readonly recoverInlineEdits: boolean;
  readonly blockAutoGenerated: boolean;
  readonly enforceSeenLines: boolean;
  readonly recordParseRegressions: boolean;
  readonly autoRepairParseRegressions: boolean;
};

export type FilesReadingPolicy = {
  readonly lineNumbers: boolean;
  readonly defaultLimit: number;
  readonly renderMarkdown: boolean;
};

export type FilesReadSummariesPolicy = {
  readonly enabled: boolean;
  readonly prose: boolean;
  readonly minBodyLines: number;
  readonly minCommentLines: number;
  readonly minTotalLines: number;
  readonly unfoldUntil: number;
  readonly unfoldLimit: number;
};

export type FilesEditingPolicySnapshot = {
  readonly folder: FolderPath | null;
  readonly revision: Revision;
  readonly values: FilesEditingPolicy;
};

export type FilesReadingPolicySnapshot = {
  readonly folder: FolderPath | null;
  readonly revision: Revision;
  readonly values: FilesReadingPolicy;
};

export type FilesReadSummariesPolicySnapshot = {
  readonly folder: FolderPath | null;
  readonly revision: Revision;
  readonly values: FilesReadSummariesPolicy;
};

function policyValue<T extends string | number | boolean>(
  descriptor: SettingsSectionDescriptor,
  snapshot: ConfigSnapshot,
  key: string,
  schema: z.ZodType<T>,
): T {
  const control = descriptor.controls.find((candidate) => candidate.key === key);
  if (!control) {
    throw new AppFailure({
      code: "unavailable",
      message: "Files policy settings are unavailable.",
      retryable: false,
    });
  }

  const entry = effectiveEntry(snapshot, key);
  let rawValue: JsonValue;
  if (entry) {
    if (entry.secret) {
      throw new AppFailure({
        code: "unavailable",
        message: "Files policy settings are unavailable.",
        retryable: false,
      });
    }
    rawValue = entry.value;
  } else if (hasFilesSettingDefault(key)) {
    rawValue = FILES_SETTING_DEFAULTS[key].value;
  } else {
    throw new AppFailure({
      code: "unavailable",
      message: "Files policy settings are unavailable.",
      retryable: false,
    });
  }

  const parsed = schema.safeParse(rawValue);
  if (!parsed.success) {
    throw new AppFailure({
      code: "invalid_args",
      message: "A Files setting has an invalid value.",
      retryable: false,
    });
  }
  const result = validate(control, { secret: false, value: parsed.data }, snapshot);
  if (!result.valid) {
    throw new AppFailure({ code: "invalid_args", message: result.message, retryable: false });
  }
  return parsed.data;
}

export function selectFilesEditingPolicy(snapshot: ConfigSnapshot): FilesEditingPolicySnapshot {
  return {
    folder: snapshot.folder,
    revision: snapshot.revision,
    values: {
      mode: policyValue(FILES_EDITING_SECTION, snapshot, "edit.mode", fileEditModeSchema),
      fuzzyMatch: policyValue(FILES_EDITING_SECTION, snapshot, "edit.fuzzyMatch", booleanSchema),
      fuzzyThreshold: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.fuzzyThreshold",
        numberSchema,
      ),
      streamingAbort: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.streamingAbort",
        booleanSchema,
      ),
      recoverInlineEdits: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.recoverInlineEdits",
        booleanSchema,
      ),
      blockAutoGenerated: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.blockAutoGenerated",
        booleanSchema,
      ),
      enforceSeenLines: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.enforceSeenLines",
        booleanSchema,
      ),
      recordParseRegressions: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.blackbox.enabled",
        booleanSchema,
      ),
      autoRepairParseRegressions: policyValue(
        FILES_EDITING_SECTION,
        snapshot,
        "edit.autoRepair.enabled",
        booleanSchema,
      ),
    },
  };
}

