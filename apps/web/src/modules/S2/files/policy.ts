import type { FolderPath, JsonValue, Revision } from "@omp-app/contracts";
import { AppFailure } from "@omp-app/contracts";
import { z } from "zod";
import type { ConfigSnapshot, SettingsSectionDescriptor } from "../../S1/settings-kit";
