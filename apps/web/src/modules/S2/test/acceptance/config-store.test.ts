function conflictRuntime(fixture: typeof S2_CONFLICT_FIXTURE) {
  let listCalls = 0;
  let writes = 0;
  const client: ConfigStoreClient = {
    read: async ({ key }) => {
      const entry = fixture.remote.entries.find((candidate) => candidate.key === key);
      if (entry === undefined)
        throw new AppFailure({ code: "not_found", message: "Missing", retryable: false });
      return entry;
    },
    list: async () => {
      listCalls += 1;
      return listCalls === 1
        ? { ...fixture.local.snapshot, entries: [...fixture.local.snapshot.entries] }
        : { ...fixture.remote, entries: [...fixture.remote.entries] };
    },
    write: async (args) => {
      writes += 1;
      if (writes === 1) {
        throw new AppFailure({
          code: "conflict",
          message: "Settings changed elsewhere",
          retryable: true,
        });
      }
      const value = args.value;
      const entry = value.secret
        ? {
            key: args.key,
            secret: true,
            isSet: value.action === "set",
            source: args.layer,
            overrides: [],
          }
        : {
            key: args.key,
            secret: false,
            value: value.value,
            source: args.layer,
            overrides: [],
          };
      return {
        key: args.key,
        layer: args.layer,
        folder: args.folder,
        revision: "s2-written-revision" as Revision,
        previousRevision: args.expectedRevision,
        entry,
      } as unknown as ConfigWriteResult;
    },
  };
  const changes: ConfigChangeSource = { subscribe: () => () => undefined };
  return {
    runtime: new SettingsRuntime(client, changes, {
      descriptor: SHELL_BASH_SECTION,
      folder: fixture.remote.folder,
      layer: "project",
    }),
    writeCount: () => writes,
  };
}

describe("S2.5 ConfigStore fixtures and gate coverage", () => {
  test("covers every S5 Files and Shell inventory row and its registered count", () => {
    const fixtureRows = S2_CONFIG_GROUP_FIXTURES.flatMap((group) => group.descriptor.inventory);
    expect(new Set(fixtureRows)).toEqual(new Set(inventoryRows.map((row) => row.id)));
    for (const group of S2_CONFIG_GROUP_FIXTURES) {
      const row = inventoryRows.find((candidate) => candidate.id === group.descriptor.inventory[0]);
      expect(row).toBeDefined();
      const registeredCount = Number(row?.name.match(/\((\d+)\)$/)?.[1]);
      const count =
        group.descriptor.inventory[0] === "S5.files-lsp" ||
        group.descriptor.inventory[0] === "S5.shell-bash"
          ? registeredCount + 1
          : registeredCount;
      expect(group.snapshot.entries).toHaveLength(count);
      expect(group.snapshot.entries.map((entry) => entry.key)).toEqual(
        group.descriptor.controls.map((control) => control.key),
      );
      expect(group.snapshot.revision).toBeTruthy();
      expect(group.snapshot.entries.every((entry) => entry.source === "default")).toBe(true);
      for (const entry of group.snapshot.entries) {
        if (!entry.secret) expect(EXPECTED_DEFAULTS.get(entry.key)).toEqual(entry.value);
      }
    }
  });

  test("reuses exact S1 provenance labels for every synthetic layer variant", () => {
    expect(new Set(S2_PROVENANCE_FIXTURES.map((entry) => entry.source))).toEqual(
      new Set(S2_CONFIG_SOURCES),
    );
    for (const entry of S2_PROVENANCE_FIXTURES) {
      expect(settingSourceLabel(entry.source)).toBe(SOURCE_LABELS[entry.source]);
      expect(provenanceLabel(entry)).toBe(S2_FIXTURE_HELPERS.provenance(entry));
    }
    expect(applyStatusLabel("applied")).toBe("Applied");
    expect(applyStatusLabel("reload-required")).toBe("Reload required");
    expect(applyStatusLabel("restart-required")).toBe("Restart required");
    expect(applyStatusLabel("session-only")).toBe("This session only");
    expect(applyStatusLabel("unsupported")).toBe("Unavailable");
  });

  test("keeps A1 provider secrets status-only for set and unset entries", () => {
    for (const entry of S2_SECRET_FIXTURES) {
      if (!entry.secret) throw new Error("Secret fixture must be redacted.");
      expect(entry.key).toBe("provider.apiKey");
      expect(entry.source).toBe("global");
      expect(S2_FIXTURE_HELPERS.secret(entry)).toMatchObject({
        isSecret: true,
        isSet: entry.isSet,
        source: entry.source,
      });
      expect(JSON.stringify(entry)).not.toMatch(/token|password|secretValue/i);
    }
  });

  test("runs the stale CAS fixture through S1 SettingsRuntime", async () => {
    const { runtime, writeCount } = conflictRuntime(S2_CONFLICT_FIXTURE);
    try {
      await runtime.read();
      expect(runtime.stage("bash.direnvLoadTimeoutMs", { secret: false, value: 45_000 }).ok).toBe(
        true,
      );
      await expect(runtime.save()).rejects.toMatchObject({ appError: { code: "conflict" } });
      expect(runtime.getSnapshot().conflict?.changedKeys).toEqual(S2_CONFLICT_FIXTURE.changedKeys);
      expect(runtime.getSnapshot().conflict?.local.edits).toEqual(S2_CONFLICT_FIXTURE.local.edits);
      expect(
        runtime
          .getSnapshot()
          .conflict?.remote.entries.find((entry) => entry.key === "bash.direnvLoadTimeoutMs"),
      ).toMatchObject({ source: "project", value: 60_000 });
      runtime.resolveConflict("keep-mine");
      await runtime.save();
      expect(writeCount()).toBe(2);
      expect(runtime.getSnapshot().phase).toBe("ready");
    } finally {
      runtime.dispose();
    }
  });

  test("C0 scrub check covers every exported fixture, including conflict and redaction variants", () => {
    expect(
      checkScrubbed(
        JSON.stringify({
          groups: S2_CONFIG_GROUP_FIXTURES,
          provenance: S2_PROVENANCE_FIXTURES,
          secrets: S2_SECRET_FIXTURES,
          conflict: S2_CONFLICT_FIXTURE,
          sources: S2_CONFIG_SOURCES,
        }),
      ),
    ).toEqual([]);
  });
});
